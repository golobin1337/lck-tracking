// Rate limit simples em memória (janela fixa por chave/IP).
// Baseline para um único processo. Para escalar horizontalmente, trocar
// por Redis/Upstash. Suficiente para proteção básica dos endpoints públicos.

type Bucket = { count: number; resetAt: number }

const buckets = new Map<string, Bucket>()

// Limpeza preguiçosa para não crescer indefinidamente.
let lastSweep = Date.now()
function sweep(now: number) {
  if (now - lastSweep < 60_000) return
  lastSweep = now
  for (const [key, b] of buckets) {
    if (b.resetAt <= now) buckets.delete(key)
  }
}

export function rateLimit(
  key: string,
  limit = 60,
  windowMs = 60_000
): { allowed: boolean; remaining: number; resetAt: number } {
  const now = Date.now()
  sweep(now)

  const existing = buckets.get(key)
  if (!existing || existing.resetAt <= now) {
    const resetAt = now + windowMs
    buckets.set(key, { count: 1, resetAt })
    return { allowed: true, remaining: limit - 1, resetAt }
  }

  existing.count += 1
  const allowed = existing.count <= limit
  return {
    allowed,
    remaining: Math.max(0, limit - existing.count),
    resetAt: existing.resetAt,
  }
}
